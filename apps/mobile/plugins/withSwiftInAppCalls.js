/**
 * [INAPP-CALLS · owner 6 Nov 2026, "B"] Android wiring for in-app calls
 * (@twilio/voice-react-native-sdk 1.8.x), written by Swift instead of using the
 * SDK's own config plugin as-is. Read from the SDK package itself (1.8.1):
 *
 * 1. The SDK's plugin makes MainActivity call VoiceActivityProxy.onCreate(), which
 *    asks for the microphone, Bluetooth and notifications permissions on EVERY app
 *    start (no explanation, even while calls are off) and adds
 *    FLAG_SHOW_WHEN_LOCKED | FLAG_TURN_SCREEN_ON | FLAG_KEEP_SCREEN_ON to Swift's
 *    main window for good (Swift over the lock screen, the screen never sleeping).
 *    Swift forwards ONLY the SDK's own call intents to its VoiceService, and only
 *    when the intent names a call the SDK holds right now (its random call UUID:
 *    MainActivity is exported, so another app's intent is never trusted; security
 *    review, confused deputy); shows over the lock screen only for that ringing /
 *    answered call and clears it when no call is left; never keeps the screen on;
 *    and asks for the microphone itself, in plain words, when a call needs it.
 * 2. The SDK's manifest registers VoiceFirebaseMessagingService for
 *    com.google.firebase.MESSAGING_EVENT at the default priority; expo-notifications
 *    registers ExpoFirebaseMessagingService at priority -1. Twilio's would win and
 *    it drops every message that is not a Twilio call: every Swift push on Android
 *    (job offers, order updates) would be lost. Swift removes BOTH and registers
 *    one router, SwiftMessagingService (extends Expo's service, which is `open`):
 *    a Twilio call payload (keys "twi_...") goes to the SDK's own handler,
 *    everything else to Expo exactly as before.
 *
 * MainApplication gets the SDK's VoiceApplicationProxy (onCreate/onTerminate), as
 * the SDK documents. The app module compiles against firebase-messaging and
 * voice-android as compileOnly, at the exact versions the libraries ship
 * (runtime copies come from those libraries; versions held by a test).
 *
 * iOS needs no code here: app.config.ts adds the `voip` + `audio` background modes
 * and the microphone purpose string; the SDK's own PushKit registry reports every
 * VoIP push to CallKit.
 *
 * NOT COMPILED IN THIS REPO (no local native builds): needs a native review and an
 * EAS development build + two-phone test before build 13 (DESIGN.md §11).
 */
