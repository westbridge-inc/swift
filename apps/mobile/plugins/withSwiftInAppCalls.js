const TAG = 'swift-inapp-calls';
const PACKAGE = 'gy.swift.app.calls';
/** Exactly what the libraries ship (expo-notifications 56: firebase-messaging; the SDK 1.8.1: voiceAndroid). */
const FIREBASE_MESSAGING_VERSION = '25.0.1';
const VOICE_ANDROID_VERSION = '6.10.3';

const TWILIO_FCM_SERVICE = 'com.twiliovoicereactnative.VoiceFirebaseMessagingService';
const EXPO_FCM_SERVICE = 'expo.modules.notifications.service.ExpoFirebaseMessagingService';
const ROUTER_SERVICE = `${PACKAGE}.SwiftMessagingService`;

/** The SDK's own activity intent actions (com.twiliovoicereactnative.Constants) that Swift forwards to its
 *  VoiceService, minus ACTION_PUSH_APP_TO_FOREGROUND (it only opens the app). */
const CALL_ACTIONS = [
  'ACTION_ACCEPT_CALL',
  'ACTION_REJECT_CALL',
  'ACTION_CANCEL_ACTIVE_CALL_NOTIFICATION',
  'ACTION_INCOMING_CALL',
  'ACTION_CANCEL_CALL',
  'ACTION_CALL_DISCONNECT',
  'ACTION_RAISE_OUTGOING_CALL_NOTIFICATION',
  'ACTION_FOREGROUND_AND_DEPRIORITIZE_INCOMING_CALL_NOTIFICATION',
];
/** The incoming-call notification's full-screen / tap intent, and Answer: only these may show Swift over the
 *  lock screen, and only while the SDK holds that very call. */
const OVER_LOCK_ACTIONS = ['ACTION_FOREGROUND_AND_DEPRIORITIZE_INCOMING_CALL_NOTIFICATION', 'ACTION_ACCEPT_CALL'];
/** The extra the SDK's own PendingIntents carry (Constants.MSG_KEY_UUID): the call record's random UUID. */
const CALL_UUID_EXTRA = 'UUID';

const ROUTER_KT = `package ${PACKAGE}

// @generated by ${TAG} (plugins/withSwiftInAppCalls.js). Do not edit: regenerated on prebuild.
import android.os.PowerManager
import android.util.Log
import com.google.firebase.messaging.RemoteMessage
import com.twilio.voice.Voice
import com.twiliovoicereactnative.CallMessageListenerProxy
import com.twiliovoicereactnative.VoiceFirebaseMessagingService
import expo.modules.notifications.service.ExpoFirebaseMessagingService

/**
 * The ONE receiver of Firebase messages. A Twilio call payload goes to the SDK's own handler (the call
 * notification) and NEVER on to Expo, even when the SDK refuses or throws (logged); every other message goes
 * to expo-notifications exactly as before.
 */
class SwiftMessagingService : ExpoFirebaseMessagingService() {
  override fun onMessageReceived(remoteMessage: RemoteMessage) {
    val data = remoteMessage.data
    if (data.keys.any { it.startsWith("twi_") }) {
      // The SDK's own service wakes a dark screen for 30 seconds so the incoming call is seen: the same here.
      try {
        val pm = getSystemService(POWER_SERVICE) as PowerManager
        if (!pm.isInteractive) {
          @Suppress("DEPRECATION")
          pm.newWakeLock(PowerManager.SCREEN_DIM_WAKE_LOCK or PowerManager.ACQUIRE_CAUSES_WAKEUP, "SwiftMessagingService:incomingCall").acquire(30000)
        }
      } catch (e: Throwable) {
        Log.w(TAG, "could not wake the screen for an incoming call", e)
      }
      try {
        if (!Voice.handleMessage(this, data, VoiceFirebaseMessagingService.MessageHandler(), CallMessageListenerProxy())) {
          Log.w(TAG, "a Twilio message the call SDK did not accept")
        }
      } catch (e: Throwable) {
        Log.e(TAG, "the call SDK failed on a Twilio message", e)
      }
      return
    }
    super.onMessageReceived(remoteMessage)
  }

  companion object {
    private const val TAG = "SwiftMessagingService"
  }
}
`;

/**
 * [SECURITY REVIEW, MEDIUM: confused deputy] MainActivity is exported (it is the launcher), and the SDK's own
 * notification PendingIntents target it (VoiceApplicationProxy.getMainActivityClass() = the launch activity),
 * so a non-exported activity cannot take them. Instead every call intent must carry the UUID of a call record
 * the SDK holds RIGHT NOW (a random UUID only the SDK and its own PendingIntents know). Any other app's
 * intent (no UUID, a guessed one, an ended call) is never forwarded and never shows Swift over the lock screen.
 * This file lives in the SDK's package because its call database is package-private there (same APK, same
 * class loader, same runtime package).
 */
const GATE_KT = `package com.twiliovoicereactnative

// @generated by ${TAG} (plugins/withSwiftInAppCalls.js). Do not edit: regenerated on prebuild.
import java.util.UUID

/** Does the call SDK hold this call (a live invite or call) right now? Any failure answers no. */
object SwiftCallGate {
  @JvmStatic
  fun holdsCall(uuid: Any?): Boolean {
    if (uuid !is UUID) return false
    return try {
      VoiceApplicationProxy.getCallRecordDatabase().get(CallRecordDatabase.CallRecord(uuid)) != null
    } catch (e: Throwable) {
      false
    }
  }

  @JvmStatic
  fun anyCall(): Boolean = try {
    VoiceApplicationProxy.getCallRecordDatabase().getCollection().isNotEmpty()
  } catch (e: Throwable) {
    false
  }
}
`;

const INTENTS_KT = `package ${PACKAGE}

// @generated by ${TAG} (plugins/withSwiftInAppCalls.js). Do not edit: regenerated on prebuild.
import android.app.Activity
import android.app.Application
import android.content.Intent
import android.os.Build
import android.os.Bundle
import android.view.WindowManager
import com.twiliovoicereactnative.SwiftCallGate

/**
 * Forwards ONLY the call SDK's own intents for a call it holds right now to its VoiceService. Never keeps the
 * screen on. Shows Swift over the lock screen only for a ringing / answered call the SDK holds, and clears it
 * whenever the activity pauses, stops or resumes with no call left.
 */
object SwiftCallIntents {
  private val CALL_ACTIONS = setOf(${CALL_ACTIONS.map((a) => `"${a}"`).join(', ')})
  private val OVER_LOCK_ACTIONS = setOf(${OVER_LOCK_ACTIONS.map((a) => `"${a}"`).join(', ')})
  private const val CALL_UUID_EXTRA = "${CALL_UUID_EXTRA}"
  private var watching = false

  @JvmStatic
  fun forward(activity: Activity, intent: Intent?) {
    watch(activity)
    val action = intent?.action
    @Suppress("DEPRECATION")
    val uuid = try { intent?.getSerializableExtra(CALL_UUID_EXTRA) } catch (e: Throwable) { null }
    if (action == null || action !in CALL_ACTIONS || !SwiftCallGate.holdsCall(uuid)) {
      // Not the SDK's intent for a call it holds (another app, a stale or guessed id): nothing is forwarded.
      if (!SwiftCallGate.anyCall()) showOverLockScreen(activity, false)
      return
    }
    showOverLockScreen(activity, action in OVER_LOCK_ACTIONS)
    val copy = Intent(intent)
    copy.setClassName(activity.applicationContext, "com.twiliovoicereactnative.VoiceService")
    copy.flags = 0
    try {
      activity.applicationContext.startService(copy)
    } catch (e: Throwable) {
      // The call notification still offers Answer / Decline.
    }
  }

  /** Once per process: re-check on every pause / stop / resume and clear the lock-screen flags when no call is left. */
  private fun watch(activity: Activity) {
    if (watching) return
    watching = true
    activity.application.registerActivityLifecycleCallbacks(object : Application.ActivityLifecycleCallbacks {
      private fun recheck(a: Activity) { if (!SwiftCallGate.anyCall()) showOverLockScreen(a, false) }
      override fun onActivityResumed(a: Activity) = recheck(a)
      override fun onActivityPaused(a: Activity) = recheck(a)
      override fun onActivityStopped(a: Activity) = recheck(a)
      override fun onActivityCreated(a: Activity, b: Bundle?) {}
      override fun onActivityStarted(a: Activity) {}
      override fun onActivitySaveInstanceState(a: Activity, b: Bundle) {}
      override fun onActivityDestroyed(a: Activity) {}
    })
  }

  private fun showOverLockScreen(activity: Activity, on: Boolean) {
    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O_MR1) {
      activity.setShowWhenLocked(on)
      activity.setTurnScreenOn(on)
    } else {
      @Suppress("DEPRECATION")
      val flags = WindowManager.LayoutParams.FLAG_SHOW_WHEN_LOCKED or WindowManager.LayoutParams.FLAG_TURN_SCREEN_ON
      if (on) activity.window.addFlags(flags) else activity.window.clearFlags(flags)
    }
  }
}
`;

/* ------------------------------------------------------------ pure edits */

function addImport(src, line) {
  if (src.split('\n').some((l) => l.trim() === line)) return src;
  const lines = src.split('\n');
  let last = -1;
  for (let i = 0; i < lines.length; i++) if (/^import\s/.test(lines[i])) last = i;
  if (last === -1) throw new Error(`${TAG}: no import block found`);
  lines.splice(last + 1, 0, line);
  return lines.join('\n');
}

/** Index of the `}` closing the class body that opens at the first `{` after `classRe`. Counts braces outside strings/comments. */
function classBounds(src, classRe) {
  const m = src.match(classRe);
  if (!m) return null;
  const open = src.indexOf('{', m.index + m[0].length - 1);
  if (open === -1) return null;
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const two = src.substr(i, 2);
    if (two === '//') { i = src.indexOf('\n', i); if (i === -1) return null; continue; }
    if (two === '/*') { i = src.indexOf('*/', i + 2) + 1; if (i === 0) return null; continue; }
    const c = src[i];
    if (c === '"') { i += 1; while (i < src.length && src[i] !== '"') { if (src[i] === '\\') i += 1; i += 1; } continue; }
    if (c === '{') depth += 1;
    else if (c === '}') { depth -= 1; if (depth === 0) return { open, close: i }; }
  }
  return null;
}

/** Insert `stmt` right after the first `anchor` inside the method matched by `sigRe`. Throws if absent. */
function afterInMethod(src, sigRe, anchor, stmt, what) {
  const m = src.match(sigRe);
  if (!m) throw new Error(`${TAG}: could not find ${what}`);
  const open = src.indexOf('{', m.index + m[0].length - 1);
  const at = src.indexOf(anchor, open);
  const nextFun = src.indexOf('fun ', open + 1);
  if (at === -1 || (nextFun !== -1 && at > nextFun)) throw new Error(`${TAG}: ${what} does not call ${anchor}`);
  const end = at + anchor.length;
  return `${src.slice(0, end)}\n    ${stmt} // @generated by ${TAG}${src.slice(end)}`;
}

/** MainApplication.kt: the SDK's VoiceApplicationProxy, as its docs wire it. Idempotent. */
function wireMainApplication(src) {
  if (src.includes(`@generated by ${TAG}`)) return src;
  if (/override\s+fun\s+onTerminate/.test(src)) throw new Error(`${TAG}: MainApplication already overrides onTerminate; wire VoiceApplicationProxy by hand`);
  let out = addImport(src, 'import com.twiliovoicereactnative.VoiceApplicationProxy');
  const b = classBounds(out, /class\s+MainApplication\s*:[^{]*/);
  if (!b) throw new Error(`${TAG}: could not find class MainApplication`);
  out = `${out.slice(0, b.close)}
  // @generated by ${TAG}
  override fun onTerminate() {
    voiceApplicationProxy.onTerminate()
    super.onTerminate()
  }
${out.slice(b.close)}`;
  out = `${out.slice(0, b.open + 1)}
  // @generated by ${TAG}
  private val voiceApplicationProxy = VoiceApplicationProxy(this)
${out.slice(b.open + 1)}`;
  return afterInMethod(out, /override\s+fun\s+onCreate\s*\(\s*\)\s*/, 'super.onCreate()', 'voiceApplicationProxy.onCreate()', 'MainApplication.onCreate()');
}

/** MainActivity.kt: forward the SDK's call intents (onCreate + onNewIntent). No permission prompt, no window flags. Idempotent. */
function wireMainActivity(src) {
  if (src.includes(`@generated by ${TAG}`)) return src;
  if (/override\s+fun\s+onNewIntent/.test(src)) throw new Error(`${TAG}: MainActivity already overrides onNewIntent; add ${PACKAGE}.SwiftCallIntents.forward(this, intent) to it by hand`);
  let out = addImport(src, 'import android.content.Intent');
  out = addImport(out, `import ${PACKAGE}.SwiftCallIntents`);
  const b = classBounds(out, /class\s+MainActivity\s*:[^{]*/);
  if (!b) throw new Error(`${TAG}: could not find class MainActivity`);
  out = `${out.slice(0, b.close)}
  // @generated by ${TAG}
  override fun onNewIntent(intent: Intent) {
    super.onNewIntent(intent)
    SwiftCallIntents.forward(this, intent)
  }
${out.slice(b.close)}`;
  const m = out.match(/super\.onCreate\([^)]*\)/);
  if (!m) throw new Error(`${TAG}: MainActivity.onCreate does not call super.onCreate(...)`);
  return afterInMethod(out, /override\s+fun\s+onCreate\s*\(\s*savedInstanceState\s*:\s*Bundle\?\s*\)\s*/, m[0], 'SwiftCallIntents.forward(this, intent)', 'MainActivity.onCreate(Bundle?)');
}

/** app/build.gradle: compile against the two libraries' classes the router uses (runtime copies come from them). Idempotent. */
function wireAppGradle(src) {
  if (src.includes(`@generated by ${TAG}`)) return src;
  const at = src.search(/^dependencies\s*\{/m);
  if (at === -1) throw new Error(`${TAG}: app/build.gradle has no dependencies block`);
  const open = src.indexOf('{', at);
  return `${src.slice(0, open + 1)}
    // @generated by ${TAG}: compile-only, the runtime copies come from expo-notifications and the call SDK.
    compileOnly("com.google.firebase:firebase-messaging:${FIREBASE_MESSAGING_VERSION}")
    compileOnly("com.twilio:voice-android:${VOICE_ANDROID_VERSION}")${src.slice(open + 1)}`;
}

/** AndroidManifest (parsed xml2js object): exactly one Firebase receiver, the router. Idempotent. */
function wireManifest(manifest) {
  manifest.manifest.$ = manifest.manifest.$ || {};
  manifest.manifest.$['xmlns:tools'] = manifest.manifest.$['xmlns:tools'] || 'http://schemas.android.com/tools';
  const app = manifest.manifest.application[0];
  const services = (app.service || []).filter((s) => ![TWILIO_FCM_SERVICE, EXPO_FCM_SERVICE, ROUTER_SERVICE].includes(s.$['android:name']));
  services.push(
    { $: { 'android:name': TWILIO_FCM_SERVICE, 'tools:node': 'remove' } },
    { $: { 'android:name': EXPO_FCM_SERVICE, 'tools:node': 'remove' } },
    {
      $: { 'android:name': ROUTER_SERVICE, 'android:exported': 'false' },
      'intent-filter': [{ action: [{ $: { 'android:name': 'com.google.firebase.MESSAGING_EVENT' } }] }],
    },
  );
  app.service = services;
  return manifest;
}

/* ---------------------------------------------------------------- plugin */

const withSwiftInAppCalls = (config) => {
  config = withMainApplication(config, (cfg) => {
    if (cfg.modResults.language !== 'kt') throw new Error(`${TAG}: MainApplication must be Kotlin`);
    cfg.modResults.contents = wireMainApplication(cfg.modResults.contents);
    return cfg;
  });
  config = withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== 'kt') throw new Error(`${TAG}: MainActivity must be Kotlin`);
    cfg.modResults.contents = wireMainActivity(cfg.modResults.contents);
    return cfg;
  });
  config = withAppBuildGradle(config, (cfg) => {
    cfg.modResults.contents = wireAppGradle(cfg.modResults.contents);
    return cfg;
  });
  config = withAndroidManifest(config, (cfg) => {
    cfg.modResults = wireManifest(cfg.modResults);
    return cfg;
  });
  config = withDangerousMod(config, ['android', (cfg) => {
    const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java', ...PACKAGE.split('.'));
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, 'SwiftMessagingService.kt'), ROUTER_KT);
    fs.writeFileSync(path.join(dir, 'SwiftCallIntents.kt'), INTENTS_KT);
    const gateDir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/java/com/twiliovoicereactnative');
    fs.mkdirSync(gateDir, { recursive: true });
    fs.writeFileSync(path.join(gateDir, 'SwiftCallGate.kt'), GATE_KT);
    return cfg;
  }]);
  return config;
};

module.exports = createRunOncePlugin(withSwiftInAppCalls, TAG, '1');
module.exports.internals = {
  wireMainApplication, wireMainActivity, wireAppGradle, wireManifest,
  ROUTER_KT, INTENTS_KT, GATE_KT, CALL_ACTIONS, OVER_LOCK_ACTIONS, CALL_UUID_EXTRA,
  FIREBASE_MESSAGING_VERSION, VOICE_ANDROID_VERSION, TWILIO_FCM_SERVICE, EXPO_FCM_SERVICE, ROUTER_SERVICE,
};
