export class ReviewTenantRefusedError extends Error {
  constructor(slug: string, why: string) {
    super(`[STA-1] content pack refused for "${slug}": ${why}`);
    this.name = 'ReviewTenantRefusedError';
  }
}

/** The ONLY tenant the pack may touch: an existing, purge-protected REVIEW tenant. */
export async function assertReviewTenant(prisma: PrismaClient, slug: string): Promise<{ id: string }> {
  if (!REVIEW_SLUG_PATTERN.test(slug)) throw new ReviewTenantRefusedError(slug, 'the slug must match /^review-[a-z0-9-]{2,40}$/');
  const tenant = await prisma.tenant.findUnique({ where: { id: slug }, select: { id: true, kind: true, purgeProtected: true } });
  if (!tenant) throw new ReviewTenantRefusedError(slug, 'no such tenant — run review:provision first');
  if (tenant.kind !== 'REVIEW') throw new ReviewTenantRefusedError(slug, `the tenant is ${tenant.kind}, not REVIEW`);
  if (!tenant.purgeProtected) throw new ReviewTenantRefusedError(slug, 'the tenant is not purge-protected');
  return { id: tenant.id };
}

