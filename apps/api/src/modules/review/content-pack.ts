const PICTURE = /^([a-z0-9-]{1,48})--([a-z0-9-]{1,48})\.png$/;
const pictureCache = new Map<string, Buffer>();

/**
 * The PNG for `<store>--<item>.png` under REVIEW_PACK_IMAGE_DIR, or null when
 * the pack declares no such picture. Bounded: at most one cached buffer per
 * item the pack declares.
 */
export function reviewPackPicture(file: string): Buffer | null {
  const m = PICTURE.exec(file);
  if (!m) return null;
  const cached = pictureCache.get(file);
  if (cached) return cached;
  const store = REVIEW_PACK_STORES.find((s) => s.key === m[1]);
  const item = store?.categories.flatMap((c) => c.items).find((i) => i.key === m[2]);
  if (!store || !item || !isLetterable(item.name) || !isLetterable(store.name)) return null;
  const png = renderPackPicture({ title: item.name, caption: store.name, background: store.colour });
  pictureCache.set(file, png);
  return png;
}
