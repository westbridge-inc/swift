export type ContentPackState = 'ABSENT' | 'INCOMPLETE' | 'PRESENT';
export interface ContentPackFacts {
  state: ContentPackState;
  expectedStores: number;
  stores: number;
  /** ACTIVE + verified + open + accepting orders: what a reviewer can order from. */
  orderableStores: number;
  expectedItems: number;
  items: number;
  /** The rider and taxi driver logins, and how many would pass the go-online document gate. */
  partners: ReviewPartnerFacts;
}

export interface ContentPackSeedResult extends ContentPackFacts {
  tenantId: string;
  version: string;
  categories: number;
  /** Partner fixture documents committed by this run (0 on an idempotent re-run). */
  partnerDocumentsCommitted: number;
}

/** Pick the synthetic owner's phone: deterministic per tenant, never one already taken. */
async function ownerPhoneFor(prisma: PrismaClient, tenantId: string, ownerUserId: string): Promise<string> {
  const existing = await runWithoutTenant(
    () => prisma.user.findUnique({ where: { id: ownerUserId }, select: { tenantId: true, phone: true } }),
    'review-pack-owner',
  );
  if (existing) {
    if (existing.tenantId !== tenantId) throw new ReviewTenantRefusedError(tenantId, 'the pack owner id already belongs to another tenant');
    return existing.phone;
  }
  const start = parseInt(crypto.createHash('sha256').update(tenantId).digest('hex').slice(0, 4), 16) % 100;
  for (let i = 0; i < 100; i++) {
    const phone = `${PACK_OWNER_PHONE_PREFIX}${String((start + i) % 100).padStart(2, '0')}`;
    const taken = await runWithoutTenant(
      () => prisma.user.findUnique({ where: { phone }, select: { id: true } }),
      'review-pack-owner',
    );
    if (!taken) return phone;
  }
  throw new ReviewTenantRefusedError(tenantId, `every ${PACK_OWNER_PHONE_PREFIX}NN identifier is taken`);
}

/**
 * Seeds (or heals) the pack inside ONE review tenant. Idempotent; refuses any
 * tenant that is not REVIEW before the first write; never deletes.
 */
export async function seedReviewContentPack(prisma: PrismaClient, input: { slug: string }): Promise<ContentPackSeedResult> {
  const { id: tenantId } = await assertReviewTenant(prisma, input.slug);
  const plan = planReviewContentPack(tenantId);
  const ownerPhone = await ownerPhoneFor(prisma, tenantId, plan.ownerUserId);
  let partnerDocumentsCommitted = 0;

  await runWithTenant(tenantId, async () => {
    await prisma.user.upsert({
      where: { id: plan.ownerUserId, tenantId },
      create: {
        id: plan.ownerUserId, tenantId, phone: ownerPhone, firstName: 'Demo', lastName: 'Store Owner',
        roles: ['VENDOR_OWNER'], activeRole: 'VENDOR_OWNER', isSynthetic: true,
      },
      update: { firstName: 'Demo', lastName: 'Store Owner' },
    });
    await prisma.vendorOwner.upsert({
      where: { userId: plan.ownerUserId },
      create: { id: plan.vendorOwnerId, userId: plan.ownerUserId },
      update: {},
    });

    for (const { id, slug, store } of plan.vendors) {
      const place = {
        name: store.name, description: store.description, vendorType: store.vendorType,
        addressLine1: store.addressLine1, city: 'Georgetown', region: 'Demerara-Mahaica',
        latitude: LAUNCH_CITY.lat + store.offset.lat, longitude: LAUNCH_CITY.lng + store.offset.lng,
        cuisineTypes: store.cuisineTypes, tags: store.tags,
      };
      // Live inside the fiction, and only there; no MMG link, no public phone.
      const live = {
        status: 'ACTIVE' as const, isVerified: true, acceptingOrders: true, isCurrentlyOpen: true,
        mmgPayUrl: null, mmgPayUrlPending: null, mmgPayUrlPendingAt: null, mmgPayUrlApplyAt: null, publicPhone: null,
      };
      await prisma.vendor.upsert({
        where: { id, tenantId },
        create: { id, tenantId, slug, ownerId: plan.vendorOwnerId, phone: ownerPhone, isSynthetic: true, ...place, ...live },
        update: { ...place, ...live },
      });
    }

    for (const h of plan.hours) {
      await prisma.operatingHours.upsert({
        where: { id: h.id, vendorId: h.vendorId },
        create: { id: h.id, vendorId: h.vendorId, dayOfWeek: h.dayOfWeek, openTime: h.store.hours.open, closeTime: h.store.hours.close, isClosed: false },
        update: { openTime: h.store.hours.open, closeTime: h.store.hours.close, isClosed: false },
      });
    }

    for (const c of plan.categories) {
      await prisma.category.upsert({
        where: { id: c.id, tenantId },
        create: { id: c.id, tenantId, vendorId: c.vendorId, name: c.category.name, sortOrder: c.sortOrder, isActive: true },
        update: { name: c.category.name, sortOrder: c.sortOrder, isActive: true },
      });
    }

    for (const it of plan.items) {
      const service = it.store.vendorType === 'SERVICE';
      const fulfillment: FulfillmentType = service ? 'APPOINTMENT' : 'DELIVERY';
      const bookingConfig: Prisma.InputJsonValue | undefined = service
        ? {
          durationMinutes: it.item.minutes ?? 30,
          slots: Array.from({ length: 7 }, (_, dayOfWeek) => ({ dayOfWeek, start: '09:00', end: '17:00' })),
          serviceMode: 'AT_BUSINESS',
        }
        : undefined;
      // Stock is never written here (inventory/stock.ts is its one writer):
      // pack items are created untracked (stockQuantity null = always in stock).
      const fields = {
        name: it.item.name, description: it.item.description, imageUrl: packImageUrl(it.store.key, it.item.key),
        basePrice: it.item.price, fulfillment, unit: it.item.unit ?? null, sortOrder: it.sortOrder,
        isAvailable: true,
        ...(bookingConfig ? { bookingConfig } : {}),
      };
      await prisma.item.upsert({
        where: { id: it.id, tenantId },
        create: { id: it.id, tenantId, vendorId: it.vendorId, categoryId: it.categoryId, dietaryTags: [], allergens: [], ...fields },
        update: fields,
      });
    }

    // The fiction's rider and taxi driver: verified partners, inside this tenant only.
    partnerDocumentsCommitted = (await seedReviewPartners(prisma, tenantId)).documentsCommitted;
  });

  const facts = await reviewContentPackFacts(prisma, tenantId);
  return { tenantId, version: REVIEW_CONTENT_PACK_VERSION, categories: plan.categories.length, partnerDocumentsCommitted, ...facts };
}

/** At least one rider and one taxi driver login, every one of them able to go online. */
export function partnersComplete(p: ReviewPartnerFacts): boolean {
  return p.RIDER.credentials > 0 && p.DRIVER.credentials > 0
    && p.RIDER.ready === p.RIDER.credentials && p.DRIVER.ready === p.DRIVER.credentials;
}

/** What of the pack exists in `tenantId` — counted by the pack's own ids only. */
export async function reviewContentPackFacts(prisma: PrismaClient, tenantId: string): Promise<ContentPackFacts> {
  const plan = planReviewContentPack(tenantId);
  const [vendors, items, partners] = await Promise.all([
    prisma.vendor.findMany({
      where: { tenantId, id: { in: plan.vendors.map((v) => v.id) } },
      select: { status: true, isVerified: true, acceptingOrders: true, isCurrentlyOpen: true },
    }),
    prisma.item.count({ where: { tenantId, id: { in: plan.items.map((i) => i.id) }, isAvailable: true } }),
    reviewPartnerFacts(prisma, tenantId),
  ]);
  const orderableStores = vendors.filter((v) => v.status === 'ACTIVE' && v.isVerified && v.acceptingOrders && v.isCurrentlyOpen).length;
  const expectedStores = plan.vendors.length;
  const expectedItems = plan.items.length;
  const storesComplete = vendors.length === expectedStores && orderableStores === expectedStores && items === expectedItems;
  const state: ContentPackState = vendors.length === 0 && items === 0 && partners.profiles === 0
    ? 'ABSENT'
    : storesComplete && partnersComplete(partners) ? 'PRESENT' : 'INCOMPLETE';
  return { state, expectedStores, stores: vendors.length, orderableStores, expectedItems, items, partners };
}

