/**
 * [STA-1 Part 6] The store-review CONTENT PACK: what an App Store / Play
 * reviewer finds after signing in with the review credential.
 *
 * Five FICTIONAL Georgetown-style businesses — a kitchen, a grocer, a bakery &
 * cafe, a personal-care convenience store and a barber (services, booked by
 * appointment) — with menus priced in GYD, categories and opening hours. Every
 * store is ACTIVE, verified, open and accepting orders INSIDE the REVIEW
 * tenant only, so the reviewer can browse, add to the cart and reach
 * checkout. Placing the order is refused with a friendly message (the
 * review-tenant checkout rule in order.service.ts): no order, no money rail
 * (DL-5), no provider is ever touched.
 *
 *   - FICTION ONLY. No real person, business, address or phone number. Store
 *     addresses say "(demo address)"; the one synthetic owner is "Demo Store
 *     Owner" on an undialable +5920009700NN identifier (a leading 0 after +592
 *     is never a subscriber number); no store publishes a phone or an MMG link.
 *     `PACK_NAME_DENYLIST` keeps well-known real Guyanese and global brand
 *     names out of every name (content-pack test).
 *   - TENANT-WALLED. `assertReviewTenant` refuses every tenant that is not a
 *     purge-protected REVIEW tenant (swift-default and every operator
 *     included) BEFORE any write; every row names the review tenant
 *     explicitly; and with the scoped client the writes also run inside that
 *     tenant, where the wall stamps the tenant last.
 *   - IDEMPOTENT. Every row's id is derived from (pack version, tenant, logical
 *     key), and every write is an upsert keyed on that id AND the tenant — a
 *     colliding id in another tenant fails loudly instead of being adopted.
 *     Re-running heals drift (a darkened store, an edited price) back to the
 *     pack and never deletes anything (the tenant is purge-protected).
 *   - IMAGES: Swift-generated, never downloaded. Each item's picture is drawn
 *     by pack-image.ts from the pack's own words (licence/source recorded
 *     there and in PACK_IMAGE_LICENCE) and served by the public uploads route.
 *   - NO RATINGS. Ratings belong to real orders; the stores show "New".
 *   - PARTNERS. The same seed makes the tenant's RIDER and DRIVER credential
 *     accounts verified partners inside the fiction (partner-pack.ts), so
 *     a reviewer can sign in as either and go online. PRESENT includes them.
 */
