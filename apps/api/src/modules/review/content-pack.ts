/** id = rvp_<kind>_<sha256(version, tenant, kind, key)[:24]> — never random. */
export function packId(tenantId: string, kind: string, key: string): string {
  const h = crypto.createHash('sha256').update(`${REVIEW_CONTENT_PACK_VERSION}\0${tenantId}\0${kind}\0${key}`).digest('hex');
  return `rvp_${kind}_${h.slice(0, 24)}`;
}

export function packImageUrl(storeKey: string, itemKey: string): string {
  return `/uploads/items/${REVIEW_PACK_IMAGE_DIR}${storeKey}--${itemKey}.png`;
}

export interface PackPlan {
  ownerUserId: string;
  vendorOwnerId: string;
  vendors: Array<{ id: string; slug: string; store: PackStore }>;
  hours: Array<{ id: string; vendorId: string; dayOfWeek: number; store: PackStore }>;
  categories: Array<{ id: string; vendorId: string; sortOrder: number; category: PackCategory }>;
  items: Array<{ id: string; vendorId: string; categoryId: string; sortOrder: number; item: PackItem; store: PackStore }>;
}

/** Every row the pack owns in `tenantId`, with its id — pure. */
export function planReviewContentPack(tenantId: string): PackPlan {
  const plan: PackPlan = {
    ownerUserId: packId(tenantId, 'usr', 'owner'),
    vendorOwnerId: packId(tenantId, 'own', 'owner'),
    vendors: [], hours: [], categories: [], items: [],
  };
  for (const store of REVIEW_PACK_STORES) {
    const vendorId = packId(tenantId, 'ven', store.key);
    plan.vendors.push({ id: vendorId, slug: `${tenantId}-${store.key}`, store });
    for (let dow = 0; dow < 7; dow++) plan.hours.push({ id: packId(tenantId, 'hrs', `${store.key}:${dow}`), vendorId, dayOfWeek: dow, store });
    store.categories.forEach((category, ci) => {
      const categoryId = packId(tenantId, 'cat', `${store.key}:${category.key}`);
      plan.categories.push({ id: categoryId, vendorId, sortOrder: ci, category });
      category.items.forEach((item, ii) => {
        plan.items.push({ id: packId(tenantId, 'itm', `${store.key}:${item.key}`), vendorId, categoryId, sortOrder: ii, item, store });
      });
    });
  }
  return plan;
}

