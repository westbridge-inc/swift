describe('RSA-OAEP-SHA256 — interop with an independent RFC 8017 implementation', () => {
  it('MMG can open what we send: EME-OAEP with SHA-256, MGF1-SHA-256 and an empty label', () => {
    const plaintext = serializeCheckoutRequest(request());
    const ciphertext = encryptCheckoutRequest(plaintext, mmg.publicKey);
    expect(ciphertext.length).toBe(512);
    expect(emeOaepDecode(rawDecrypt(mmg.privateKey, ciphertext), 'sha256')).toEqual(plaintext);
  });

  it('we can open what MMG sends under the same parameters, padded or not', () => {
    const token = replyToken(swift.publicKey, Buffer.from(JSON.stringify({ probe: 'reply', n: 7 }), 'utf8'));
    expect(decryptCheckoutResultToken(token, swift.privateKey)).toEqual({ probe: 'reply', n: 7 });
    expect(decryptCheckoutResultToken(token.replace(/=+$/, ''), swift.privateKey)).toEqual({ probe: 'reply', n: 7 });
  });

  it('the digest and the MGF1 hash are load-bearing: SHA-1 OAEP and a SHA-1 MGF1 are neither produced nor accepted', () => {
    const plaintext = serializeCheckoutRequest(request());
    const em = rawDecrypt(mmg.privateKey, encryptCheckoutRequest(plaintext, mmg.publicKey));
    expect(() => emeOaepDecode(em, 'sha1')).toThrow(/decryption error/);
    expect(() => emeOaepDecode(em, 'sha256', 'sha1')).toThrow(/decryption error/);
    const bytes = Buffer.from('{"probe":"reply"}', 'utf8');
    for (const [hash, mgfHash] of [['sha1', 'sha1'], ['sha256', 'sha1'], ['sha1', 'sha256']] as const) {
      const token = replyToken(swift.publicKey, bytes, hash, mgfHash);
      expect(refusal(() => decryptCheckoutResultToken(token, swift.privateKey)).code, `${hash}/${mgfHash}`).toBe('TOKEN_UNREADABLE');
    }
  });

  it('every encryption is fresh (the OAEP seed is random)', () => {
    const plaintext = serializeCheckoutRequest(request());
    expect(encryptCheckoutRequest(plaintext, mmg.publicKey).equals(encryptCheckoutRequest(plaintext, mmg.publicKey))).toBe(false);
  });
});

