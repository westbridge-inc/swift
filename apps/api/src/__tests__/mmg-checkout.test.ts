describe('the token and the URL', () => {
  it('the token is standard base64 with + and / swapped and the = padding KEPT (urlsafe_b64encode), unlike Buffer base64url', () => {
    const c4096 = encryptCheckoutRequest(serializeCheckoutRequest(request()), mmg.publicKey);
    const c2048 = encryptCheckoutRequest(Buffer.from('x'), small.publicKey);
    for (const [ciphertext, pad] of [[c4096, '='], [c2048, '==']] as const) {
      const token = toCheckoutToken(ciphertext);
      expect(token).toBe(ciphertext.toString('base64').replace(/\+/g, '-').replace(/\//g, '_'));
      expect(token).toMatch(/^[A-Za-z0-9_-]+={0,2}$/);
      expect(token.endsWith(pad) && !token.endsWith(`${pad}=`)).toBe(true);
      expect(token).not.toBe(ciphertext.toString('base64url'));
      expect(decodeCheckoutToken(token)).toEqual(ciphertext);
    }
    expect(toCheckoutToken(c4096)).toHaveLength(684);
  });

  it('the URL is <page>?token=RAW&merchantId=…&X-Client-ID=… in the demo order', () => {
    const token = toCheckoutToken(encryptCheckoutRequest(serializeCheckoutRequest(request()), mmg.publicKey));
    expect(buildCheckoutUrl(MMG_CHECKOUT_UAT_URL, token, '0000000001', 'client-test'))
      .toBe(`${MMG_CHECKOUT_UAT_URL}?token=${token}&merchantId=0000000001&X-Client-ID=client-test`);
    // The '=' padding rides raw, exactly as the demo writes it; an id that
    // could break the query is percent-encoded instead.
    expect(buildCheckoutUrl(MMG_CHECKOUT_UAT_URL, token, '0000000001', 'a&b=c')).toContain(`token=${token}&`);
    expect(buildCheckoutUrl(MMG_CHECKOUT_UAT_URL, token, '0000000001', 'a&b=c')).toMatch(/&X-Client-ID=a%26b%3Dc$/);
    expect(refusal(() => buildCheckoutUrl(MMG_CHECKOUT_UAT_URL, 'a+b/c', '0000000001', 'x')).code).toBe('INVALID_REQUEST');
  });
});

describe('opening a reply token', () => {
  const utf8Reply = (text: string) => replyToken(swift.publicKey, Buffer.from(text, 'utf8'));

  it('decodes UTF-8: a UTF-8 é is é', () => {
    expect(decryptCheckoutResultToken(utf8Reply('{"message":"café"}'), swift.privateKey)).toEqual({ message: 'café' });
  });

  it('never reads it as ISO-8859-1: a bare Latin-1 é byte is refused, not guessed', () => {
    const latin1 = replyToken(swift.publicKey, Buffer.from('{"message":"caf\xe9"}', 'latin1'));
    expect(refusal(() => decryptCheckoutResultToken(latin1, swift.privateKey)).code).toBe('RESULT_NOT_JSON');
  });

  it('refuses a byte-order mark, a non-JSON reply and a non-object reply', () => {
    expect(refusal(() => decryptCheckoutResultToken(utf8Reply('\ufeff{"a":1}'), swift.privateKey)).code).toBe('RESULT_NOT_JSON');
    expect(refusal(() => decryptCheckoutResultToken(utf8Reply('not json'), swift.privateKey)).code).toBe('RESULT_NOT_JSON');
    expect(refusal(() => decryptCheckoutResultToken(utf8Reply('[1,2]'), swift.privateKey)).code).toBe('RESULT_NOT_OBJECT');
    expect(refusal(() => decryptCheckoutResultToken(utf8Reply('null'), swift.privateKey)).code).toBe('RESULT_NOT_OBJECT');
  });

  it('pads to a multiple of four and no further; a malformed token is refused, never skipped', () => {
    const token = utf8Reply('{"a":1}');
    const bare = token.replace(/=+$/, '');
    expect(bare.length % 4).toBe(3);
    expect(decryptCheckoutResultToken(bare, swift.privateKey)).toEqual({ a: 1 });
    // Wrong padding, too much padding, a standard-base64 character, a space,
    // an impossible length (4n+1) and nothing at all.
    for (const bad of [`${bare}==`, `${bare}===`, `${bare}====`, `${bare.slice(0, -1)}+`, `${bare.slice(0, 10)} ${bare.slice(10)}`, bare.slice(0, 681), '']) {
      expect(refusal(() => decryptCheckoutResultToken(bad, swift.privateKey)).code, JSON.stringify(bad.slice(-6))).toBe('TOKEN_MALFORMED');
    }
    expect(refusal(() => decryptCheckoutResultToken('A'.repeat(5000), swift.privateKey)).code).toBe('TOKEN_MALFORMED');
    // One byte short of an RSA block under this key.
    expect(refusal(() => decryptCheckoutResultToken(toCheckoutToken(decodeCheckoutToken(token).subarray(1)), swift.privateKey)).code).toBe('TOKEN_MALFORMED');
  });

  it('a reply for another key is one generic refusal', () => {
    const forStranger = replyToken(stranger.publicKey, Buffer.from('{"a":1}', 'utf8'));
    const error = refusal(() => decryptCheckoutResultToken(forStranger, swift.privateKey));
    expect(error.code).toBe('TOKEN_UNREADABLE');
    expect(error.message).not.toMatch(/oaep|padding|0x/i);
  });
});

