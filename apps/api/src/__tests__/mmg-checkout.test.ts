// -- An independent RSA-OAEP, written from RFC 8017 -----------------------------
// Agreement between Node and this code is interop evidence, not a tautology:
// it shares nothing with Node's OAEP but the raw RSA primitive.

type Hash = 'sha256' | 'sha1';
const hashLength = (hash: Hash) => createHash(hash).digest().length;
const xor = (a: Buffer, b: Buffer) => Buffer.from(a.map((byte, i) => byte ^ (b[i] as number)));

/** RFC 8017 B.2.1 — MGF1. */
function mgf1(hash: Hash, seed: Buffer, length: number): Buffer {
  const blocks: Buffer[] = [];
  for (let counter = 0; blocks.length * hashLength(hash) < length; counter += 1) {
    const c = Buffer.alloc(4);
    c.writeUInt32BE(counter);
    blocks.push(createHash(hash).update(seed).update(c).digest());
  }
  return Buffer.concat(blocks).subarray(0, length);
}

/** RFC 8017 §7.1.1 step 2 — EME-OAEP encoding with the empty label. */
function emeOaepEncode(message: Buffer, k: number, hash: Hash, mgfHash: Hash = hash): Buffer {
  const hLen = hashLength(hash);
  if (message.length > k - 2 * hLen - 2) throw new Error('message too long');
  const lHash = createHash(hash).update(Buffer.alloc(0)).digest();
  const db = Buffer.concat([lHash, Buffer.alloc(k - message.length - 2 * hLen - 2), Buffer.from([0x01]), message]);
  const seed = randomBytes(hLen);
  const maskedDb = xor(db, mgf1(mgfHash, seed, k - hLen - 1));
  const maskedSeed = xor(seed, mgf1(mgfHash, maskedDb, hLen));
  return Buffer.concat([Buffer.from([0x00]), maskedSeed, maskedDb]);
}

/** RFC 8017 §7.1.2 step 3 — EME-OAEP decoding with the empty label. */
function emeOaepDecode(em: Buffer, hash: Hash, mgfHash: Hash = hash): Buffer {
  const hLen = hashLength(hash);
  const maskedSeed = em.subarray(1, 1 + hLen);
  const maskedDb = em.subarray(1 + hLen);
  const seed = xor(maskedSeed, mgf1(mgfHash, maskedDb, hLen));
  const db = xor(maskedDb, mgf1(mgfHash, seed, em.length - hLen - 1));
  const lHash = createHash(hash).update(Buffer.alloc(0)).digest();
  let i = hLen;
  while (i < db.length && db[i] === 0x00) i += 1;
  if (em[0] !== 0x00 || !db.subarray(0, hLen).equals(lHash) || db[i] !== 0x01) throw new Error('decryption error');
  return db.subarray(i + 1);
}

const rawEncrypt = (key: KeyObject, em: Buffer) => publicEncrypt({ key, padding: constants.RSA_NO_PADDING }, em);
const rawDecrypt = (key: KeyObject, block: Buffer) => privateDecrypt({ key, padding: constants.RSA_NO_PADDING }, block);
/** A reply as MMG would produce it: RFC 8017 OAEP over the given bytes, then the demo token encoding. */
const replyToken = (to: KeyObject, bytes: Buffer, hash: Hash = 'sha256', mgfHash: Hash = hash) =>
  toCheckoutToken(rawEncrypt(to, emeOaepEncode(bytes, 512, hash, mgfHash)));

function refusal(fn: () => unknown): MmgCheckoutError {
  try {
    fn();
  } catch (error) {
    expect(error).toBeInstanceOf(MmgCheckoutError);
    return error as MmgCheckoutError;
  }
  throw new Error('expected a refusal');
}

function fatal(fn: () => unknown): string {
  try {
    fn();
  } catch (error) {
    return (error as Error).message;
  }
  throw new Error('expected a FATAL refusal');
}

