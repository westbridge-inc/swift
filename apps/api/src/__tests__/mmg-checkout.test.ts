type Pair = { publicKey: KeyObject; privateKey: KeyObject };
const rsaPair = (bits: number) => new Promise<Pair>((resolve, reject) => {
  generateKeyPair('rsa', { modulusLength: bits }, (err, publicKey, privateKey) => (err ? reject(err) : resolve({ publicKey, privateKey })));
});
const pem = (key: KeyObject) => key.export(key.type === 'private' ? { type: 'pkcs8', format: 'pem' } : { type: 'spki', format: 'pem' }).toString();

